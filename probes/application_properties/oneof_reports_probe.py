"""Separate opt-in Rust/Python validator API experiment.

Checks non-virtual oneof constraints and selected direct nested oneof payloads.
It does not replace codec type checks, follow graph IDs, or validate virtual
oneofs. Unsupported nested constraint shapes fail generation explicitly.
"""

import argparse
import json
from pathlib import Path
import re

from taut.ir.load import load_schema
from taut.ir.model import ListOf, MapOf, MsgRef
from graph_contract_probe import Contract, _variant
from oneof_fields_probe import normalize_oneofs, NAMESPACE

RUST_HEADER = '''// Generated by the isolated oneof report probe. Do not edit.
// Call explicitly; record constructors and codecs do not invoke validation.
use super::api as r;

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum PathSegment { Field(&'static str), Index(usize), Key(String) }

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ValidationIssue {
    pub code: &'static str,
    pub path: Vec<PathSegment>,
    pub message: &'static str,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ValidationReport { issues: Vec<ValidationIssue> }

impl ValidationReport {
    pub fn is_valid(&self) -> bool { self.issues.is_empty() }
    pub fn issues(&self) -> &[ValidationIssue] { &self.issues }
}

fn issue(issues: &mut Vec<ValidationIssue>, path: &[PathSegment], field: &'static str,
         code: &'static str, message: &'static str) {
    let mut location = path.to_vec();
    location.push(PathSegment::Field(field));
    issues.push(ValidationIssue { code, path: location, message });
}
'''

PYTHON_HEADER = '''"""Generated opt-in oneof validation. Does not alter construction or codecs."""
from dataclasses import dataclass
from . import api as r

@dataclass(frozen=True)
class PathSegment:
    kind: str
    value: str | int

@dataclass(frozen=True)
class ValidationIssue:
    code: str
    path: tuple[PathSegment, ...]
    message: str

@dataclass(frozen=True)
class ValidationReport:
    issues: tuple[ValidationIssue, ...]

    def is_valid(self):
        return not self.issues


def _issue(issues, path, field, code, message):
    issues.append(ValidationIssue(code, (*path, PathSegment("field", field)), message))
'''

MISSING = "oneof.payload_missing"
UNEXPECTED = "oneof.payload_unexpected"
MISSING_MESSAGE = "Selected oneof payload is missing"
UNEXPECTED_MESSAGE = "Payload is not selected by the discriminator"


def _snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def _has_constraints(schema, unions, type_ref, seen=None):
    seen = set() if seen is None else seen
    if isinstance(type_ref, ListOf):
        return _has_constraints(schema, unions, type_ref.elem, seen)
    if isinstance(type_ref, MapOf):
        return _has_constraints(schema, unions, type_ref.value, seen)
    if not isinstance(type_ref, MsgRef) or type_ref.name in seen:
        return False
    if type_ref.name in unions:
        return True
    seen.add(type_ref.name)
    return any(_has_constraints(schema, unions, field.type, seen)
               for field in schema.messages[type_ref.name].fields)


def _check_coverage(contract):
    names = [_snake(name) for name in contract.unions]
    if len(names) != len(set(names)):
        raise ValueError("Validator function-name collision")
    for name, (_, cases) in contract.unions.items():
        payloads = set(cases.values()) - {None}
        for field in contract.schema.messages[name].fields:
            if not _has_constraints(contract.schema, contract.unions, field.type):
                continue
            if field.name not in payloads or not isinstance(field.type, MsgRef) or field.type.name not in contract.unions:
                raise ValueError("Nested constraints through containers or non-case fields are outside this report probe")


def _rust(contract, name):
    record = contract.schema.messages[name]
    tag, cases = contract.unions[name]
    payloads = [field for field in record.fields if field.name in set(cases.values()) - {None}]
    suffix = _snake(name)
    lines = [f"fn collect_{suffix}(value: &r::{name}, path: &mut Vec<PathSegment>, issues: &mut Vec<ValidationIssue>) {{",
             f"    match value.{tag.name} {{"]
    for member, selected in cases.items():
        lines.append(f"        r::{tag.type.name}::{_variant(member)} => {{")
        for field in payloads:
            if field.name == selected:
                if isinstance(field.type, MsgRef) and field.type.name in contract.unions:
                    lines.extend([f"            if let Some(child) = &value.{field.name} {{",
                                  f"                path.push(PathSegment::Field({json.dumps(field.name)}));",
                                  f"                collect_{_snake(field.type.name)}(child, path, issues);",
                                  "                path.pop();", "            } else {"])
                else:
                    lines.append(f"            if value.{field.name}.is_none() {{")
                lines.extend([f"                issue(issues, path, {json.dumps(field.name)}, {json.dumps(MISSING)}, {json.dumps(MISSING_MESSAGE)});", "            }"])
            else:
                lines.extend([f"            if value.{field.name}.is_some() {{",
                              f"                issue(issues, path, {json.dumps(field.name)}, {json.dumps(UNEXPECTED)}, {json.dumps(UNEXPECTED_MESSAGE)});", "            }"])
        lines.append("        }")
    lines.extend(["    }", "}", "",
                  f"pub fn validate_{suffix}(value: &r::{name}) -> ValidationReport {{",
                  "    let mut issues = Vec::new();", "    let mut path = Vec::new();",
                  f"    collect_{suffix}(value, &mut path, &mut issues);",
                  "    ValidationReport { issues }", "}", ""])
    return "\n".join(lines)


def _python(contract, name):
    record = contract.schema.messages[name]
    tag, cases = contract.unions[name]
    payloads = [field for field in record.fields if field.name in set(cases.values()) - {None}]
    suffix = _snake(name)
    lines = [f"def _collect_{suffix}(value, path, issues):",
             f"    if not isinstance(value, r.{name}):",
             f"        issues.append(ValidationIssue('validation.type_mismatch', tuple(path), 'Expected record {name}'))",
             "        return",
             f"    discriminator = getattr(value, {tag.name!r}, None)",
             f"    if not isinstance(discriminator, r.{tag.type.name}):",
             f"        _issue(issues, path, {tag.name!r}, 'oneof.discriminator_invalid', 'Invalid oneof discriminator')",
             "        return"]
    for index, (member, selected) in enumerate(cases.items()):
        lines.append(f"    {'if' if index == 0 else 'elif'} discriminator == r.{tag.type.name}.{member}:")
        body = []
        for field in payloads:
            if field.name == selected:
                body.append(f"        if getattr(value, {field.name!r}, None) is None:")
                body.append(f"            _issue(issues, path, {field.name!r}, {MISSING!r}, {MISSING_MESSAGE!r})")
                if isinstance(field.type, MsgRef) and field.type.name in contract.unions:
                    body.extend(["        else:", f"            path.append(PathSegment('field', {field.name!r}))",
                                 f"            _collect_{_snake(field.type.name)}(value.{field.name}, path, issues)", "            path.pop()"])
            else:
                body.extend([f"        if getattr(value, {field.name!r}, None) is not None:",
                             f"            _issue(issues, path, {field.name!r}, {UNEXPECTED!r}, {UNEXPECTED_MESSAGE!r})"])
        lines.extend(body or ["        pass"])
    lines.extend(["    else:",
                  f"        _issue(issues, path, {tag.name!r}, 'oneof.discriminator_invalid', 'Invalid oneof discriminator')"])
    lines.extend(["", f"def validate_{suffix}(value):", "    issues = []",
                  f"    _collect_{suffix}(value, [], issues)",
                  "    return ValidationReport(tuple(issues))", ""])
    return "\n".join(lines)


def compile_report_validators(schema):
    normalized = normalize_oneofs(schema)
    contract = Contract(normalized, NAMESPACE)
    if contract.indices or contract.checks:
        raise ValueError("Report probe emits local oneof constraints, not graph reference checks")
    _check_coverage(contract)
    if not contract.unions:
        return normalized, ("// No non-virtual validators; virtual-group validation is deferred.\n",
                            "# No non-virtual validators; virtual-group validation is deferred.\n")
    rust = RUST_HEADER + "\n"
    python = PYTHON_HEADER + "\n"
    for name in sorted(contract.unions):
        rust += _rust(contract, name) + "\n"
        python += _python(contract, name) + "\n"
    return normalized, (rust, python)


def main():
    directory = Path(__file__).parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", type=Path, default=directory / "oneof_fields.taut.py")
    parser.add_argument("--output-prefix", type=Path, default=directory / "oneof_fields.reports")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    _, generated = compile_report_validators(load_schema(args.schema))
    for extension, source in zip(("rs", "py"), generated):
        path = Path(str(args.output_prefix) + "." + extension)
        if args.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit(f"Stale validator report probe: {path}")
        else:
            path.write_text(source)
            print(path)


if __name__ == "__main__":
    main()
